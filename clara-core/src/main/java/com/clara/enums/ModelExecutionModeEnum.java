package com.clara.enums;

/**
 * 模型执行模式：描述一次能力调用与平台的交互方式。
 *
 * <p>是什么、在哪一层：契约层（{@code com.clara.model.api}）的执行模式枚举。由模型注册信息声明
 * （如某模型支持同步与流式），调用方据此决定是走同步方法还是流式方法。
 *
 * <p>使用方法：注册与校验代码读取并声明支持的集合；调用方在发起调用前确认目标模型支持所需模式，
 * 否则由能力守卫在发送前拒绝。本枚举不承载任何行为。
 *
 * <p>不可变性与线程安全：枚举常量天然不可变，可跨线程共享。
 *
 * <p>失败语义：无——声明与比较都不会抛异常；模式不受支持时由能力守卫抛出能力错误。
 */
public enum ModelExecutionModeEnum {
    /** 一次性同步请求 / 响应。 */
    SYNCHRONOUS,
    /** 以事件流方式增量返回。 */
    STREAMING,
    /** 提交异步任务后轮询状态。 */
    ASYNCHRONOUS
}
